CREATE TABLE email_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    gmail_message_id VARCHAR(255) NOT NULL,
    gmail_thread_id VARCHAR(255) NOT NULL,
    sender TEXT NOT NULL,
    subject TEXT NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT email_messages_user_message_unique
        UNIQUE (user_id, gmail_message_id)
);

CREATE INDEX email_messages_user_thread_index
    ON email_messages (user_id, gmail_thread_id);

CREATE TABLE gmail_scan_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_message_id BIGINT NOT NULL UNIQUE
        REFERENCES email_messages (id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT gmail_scan_results_status_check CHECK (
        status IN ('PENDING_CLASSIFICATION')
    )
);
